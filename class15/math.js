const sum = (a, b) =>{
    let result = a + b;
    return result;
};
const subtraction = (a, b) =>{
    let result = a - b;
    return result;
};

const division = (a, b) =>{
    let result = a / b;
    return result;
};


const  multiplication = (a, b) =>{
    let result = a * b;
    return result;
};

const  potentiation = (a, b) =>{
    let result = a**b;
    return result;
};
 
module.exports = {sum, subtraction, division, multiplication, potentiation};    